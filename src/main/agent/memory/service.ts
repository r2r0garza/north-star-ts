async function readText(file: string): Promise<string> {
  try {
    return await readFile(file, "utf-8")
  } catch {
    return ""
  }
}

// Scratch location for atomic writes. Kept inside the install's dot-directory
// (<root>/<dataDir>/.tmp) rather than beside the target, so a workspace write
// never creates a visible file in the project tree — that churn shows up as dev
// server reloads. Falls back to a dot-prefixed sibling for targets outside a
// data dir (the state file in userData). Always on the target's own filesystem
// so the rename stays atomic.
let tempSequence = 0

function tempPathFor(file: string): string {
  const segments = file.split(path.sep)
  const dataDir = dataDirName()
  const index = segments.lastIndexOf(dataDir)
  // Pooling scratch files into one directory means basename+timestamp is not
  // unique: the category skills are all called SKILL.md and are written
  // concurrently. The sequence number is what actually disambiguates them.
  const name = `${path.basename(file)}.${process.pid}.${tempSequence++}.tmp`
  if (index > 0) {
    // Rejoin rather than path.join(...segments): a leading "" from an absolute
    // path makes path.join produce a relative path and drops the root.
    const dataRoot = segments.slice(0, index + 1).join(path.sep)
    return path.join(dataRoot, ".tmp", name)
  }
  return path.join(path.dirname(file), `.${name}`)
}

// Write-then-rename so a crash mid-write can't truncate a memory file. A torn
// state file used to reset every pointer to null and orphan pending staging.
async function writeFileAtomic(file: string, content: string): Promise<void> {
  await mkdir(path.dirname(file), { recursive: true })
  const tmp = tempPathFor(file)
  await mkdir(path.dirname(tmp), { recursive: true })
  try {
    await writeFile(tmp, content, "utf-8")
    await rename(tmp, file)
  } catch (err) {
    await rm(tmp, { force: true }).catch(() => {})
    throw err
  }
}

async function writeIfMissing(file: string, content: string): Promise<void> {
  const existing = await readText(file)
  if (existing) return
  await writeFileAtomic(file, content)
}

