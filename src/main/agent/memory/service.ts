async function ensureWorkspaceMemorySkills(
  workspaceDir?: string
): Promise<void> {
  if (workspaceDir) {
    await appendWorkspaceGitignore(workspaceDir)
    await Promise.all([
      writeIfMissing(
        categorySkillPath("knowledge", workspaceDir),
        skillScaffold("knowledge")
      ),
      writeIfMissing(
        categorySkillPath("lessons", workspaceDir),
        skillScaffold("lessons")
      ),
      writeIfMissing(recentSkillPath(workspaceDir), recentScaffold()),
    ])
    return
  }
  await writeIfMissing(recentSkillPath(), recentScaffold())
}

async function appendWorkspaceGitignore(workspaceDir: string): Promise<void> {
  const file = path.join(workspaceDir, ".gitignore")
  const data = dataDirName()
  // Memory content is the user's call to version or not; the atomic-write
  // scratch dir never is.
  const rules = [`${data}/skills/memory-*`, `${data}/.tmp/`]
  const content = await readText(file)
  const present = new Set(content.split(/\r?\n/).map((line) => line.trim()))
  const missing = rules.filter((rule) => !present.has(rule))
  if (missing.length === 0) return
  const prefix = content && !content.endsWith("\n") ? "\n" : ""
  await appendFile(file, `${prefix}${missing.join("\n")}\n`, "utf-8")
}

function emptyState(): MemoryState {
  return {
    lastConversationId: null,
    lastRecentDir: null,
    lastTurnAt: null,
    lastSwapTime: null,
    swapInProgress: false,
    knownRecentDirs: [],
  }
}

async function loadState(): Promise<MemoryState> {
  const raw = await readText(stateFile())
  if (!raw) return emptyState()
  try {
    const parsed = JSON.parse(raw) as Partial<MemoryState>
    return {
      lastConversationId:
        typeof parsed.lastConversationId === "string"
          ? parsed.lastConversationId
          : null,
      lastRecentDir:
        typeof parsed.lastRecentDir === "string" ? parsed.lastRecentDir : null,
      lastTurnAt:
        typeof parsed.lastTurnAt === "string" ? parsed.lastTurnAt : null,
      lastSwapTime:
        typeof parsed.lastSwapTime === "string" ? parsed.lastSwapTime : null,
      swapInProgress: parsed.swapInProgress === true,
      knownRecentDirs: Array.isArray(parsed.knownRecentDirs)
        ? parsed.knownRecentDirs
            .filter((dir): dir is string => typeof dir === "string")
            .slice(0, KNOWN_RECENT_DIR_CAP)
        : [],
    }
  } catch (err) {
    // A corrupt state file used to silently reset every pointer, orphaning any
    // pending staging. Atomic writes make this rare; say so when it happens.
    console.warn("[memory] state file unreadable, starting from empty:", err)
    return emptyState()
  }
}

async function saveState(state: MemoryState): Promise<void> {
  await writeFileAtomic(stateFile(), JSON.stringify(state, null, 2))
}

// The state file is one shared slot mutated by every concurrent turn. Serialize
// read-modify-write so parallel conversations can't clobber each other's
// pointers (which used to strand a workspace's staging permanently).
let stateChain: Promise<unknown> = Promise.resolve()

function withStateLock<T>(fn: () => Promise<T>): Promise<T> {
  const run = stateChain.then(fn, fn)
  stateChain = run.then(
    () => undefined,
    () => undefined
  )
  return run
}

async function updateState(
  mutate: (state: MemoryState) => void
): Promise<MemoryState> {
  return withStateLock(async () => {
    const state = await loadState()
    mutate(state)
    await saveState(state)
    return state
  })
}

function rememberRecentDir(state: MemoryState, recentDir: string): void {
  state.knownRecentDirs = [
    recentDir,
    ...state.knownRecentDirs.filter((dir) => dir !== recentDir),
  ].slice(0, KNOWN_RECENT_DIR_CAP)
}

function pendingRecentDirs(state: MemoryState): string[] {
  const dirs = [...state.knownRecentDirs]
  if (state.lastRecentDir && !dirs.includes(state.lastRecentDir)) {
    dirs.push(state.lastRecentDir)
  }
  return dirs
}

// One swap per recent dir at a time. Two concurrent swaps over the same
// category files are a lost-update race: both read, both write, one wins.
const swapChains = new Map<string, Promise<unknown>>()

function withSwapLock<T>(recentDir: string, fn: () => Promise<T>): Promise<T> {
  const prior = swapChains.get(recentDir) ?? Promise.resolve()
  const run = prior.then(fn, fn)
  swapChains.set(
    recentDir,
    run.then(
      () => undefined,
      () => undefined
    )
  )
  return run
}

function stagingRecordCount(staging: string): number {
  return (staging.match(/^### /gm) ?? []).length
}

async function shouldPromoteBeforeAppend(
  state: MemoryState,
  currentConversationId: string,
  currentRecentDir: string
): Promise<boolean> {
  if (!state.lastRecentDir) return false
  const staging = (
    await readText(stagingPathFromRecentDir(state.lastRecentDir))
  ).trim()
  if (!staging) return false

  const conversationChanged =
    !!state.lastConversationId &&
    state.lastConversationId !== currentConversationId
  const scopeChanged = state.lastRecentDir !== currentRecentDir
  const lastTurnAt = state.lastTurnAt
    ? new Date(state.lastTurnAt).getTime()
    : Number.NaN
  const inactive =
    Number.isFinite(lastTurnAt) &&
    Date.now() - lastTurnAt >= INACTIVITY_BOUNDARY_MS
  const tooManyRecords = stagingRecordCount(staging) >= STAGING_RECORD_BOUNDARY
  const tooLarge = Buffer.byteLength(staging, "utf-8") >= STAGING_BYTE_BOUNDARY

  return (
    conversationChanged ||
    scopeChanged ||
    inactive ||
    tooManyRecords ||
    tooLarge
  )
}

function resolveMemorySelection(): LlmSelection {
  const memory = settingsService.getMemory()
  return { accountId: memory.accountId, modelId: memory.modelId }
}

// Returns undefined when the model could not be reached at all (no provider,
// network/API failure). Callers treat that as "retry later", distinct from a
// model that answered with something unusable.
async function memoryComplete(
  prompt: string,
  maxOutputTokens = MEMORY_MAX_OUTPUT_TOKENS
): Promise<string | undefined> {
  try {
    const { client, model, apiMode } = resolveLlm(resolveMemorySelection())
    const res = await createCompletion(
      client,
      model,
      maxOutputTokens,
      {
        messages: [
          {
            role: "system",
            content:
              "You maintain long-term memory files for an AI agent. Return only the requested structured output.",
          },
          { role: "user", content: prompt },
        ],
      },
      [],
      apiMode
    )
    return contentToText((res as any).choices?.[0]?.message?.content).trim()
  } catch (err) {
    if (err instanceof NoActiveProviderError) {
      console.warn(`[memory] skipped: ${err.message}`)
      return undefined
    }
    console.warn("[memory] LLM call failed:", err)
    return undefined
  }
}

function contentToText(content: unknown): string {
  if (typeof content === "string") return content
  if (Array.isArray(content)) {
    return content
      .map((part: any) =>
        typeof part === "string" ? part : (part?.text ?? "")
      )
      .join("")
  }
  return ""
}

// undefined means "not parseable" — the caller has to be able to tell that
// apart from a well-formed response that happened to be empty.
function parseJsonObject(
  text: string | undefined
): Record<string, unknown> | undefined {
  if (!text) return undefined
  const fenced = /```(?:json)?\s*([\s\S]*?)\s*```/i.exec(text)
  const raw = (fenced?.[1] ?? text).trim()
  try {
    const parsed = JSON.parse(raw)
    return parsed && typeof parsed === "object" && !Array.isArray(parsed)
      ? (parsed as Record<string, unknown>)
      : undefined
  } catch {
    return undefined
  }
}

function clampMemoryFact(text: string): string {
  return text.replace(/\s+/g, " ").trim().slice(0, 500)
}

function validMemoryCategory(value: unknown): value is MemoryCategory {
  return (
    value === "identity" ||
    value === "preferences" ||
    value === "knowledge" ||
    value === "lessons"
  )
}

function validMemoryCandidateKind(
  value: unknown
): value is MemoryCandidateKind {
  return (
    value === "declarative" ||
    value === "instruction" ||
    value === "quoted_untrusted"
  )
}

// Applies to every candidate regardless of kind: attempts to rewrite the
// system's own framing, or to persist/leak secrets, are never memories.
const ALWAYS_FORBIDDEN_PATTERNS = [
  /\b(ignore|override|forget)\b.{0,60}\b(system|developer|previous|above)\b/i,
  /\b(read|reveal|print|dump|exfiltrate|upload|send|publish)\b.{0,80}\b(secrets?|tokens?|passwords?|credentials?|api keys?|private keys?)\b/i,
  /\bhidden\b.{0,80}\b(command|instruction|rule)\b/i,
]

// Applies only to candidates classified as instructions to the assistant. These
// words are ordinary domain vocabulary in a workspace that *builds* approval and
// sandbox machinery — "the approval gate lives in policy.ts" is a fact worth
// keeping, while "always bypass the approval policy" is not.
const INSTRUCTION_FORBIDDEN_PATTERNS = [
  /\b(always|never)\b.{0,80}\b(approve|allow|bypass|skip)\b/i,
  /\b(auto[- ]?mode|sandbox|allowlist|approval|policy|tool permissions?)\b/i,
  /\b(install|create|enable|load)\b.{0,80}\b(skill|mcp|plugin|agent)\b/i,
]

function isForbiddenMemoryText(text: string): boolean {
  return ALWAYS_FORBIDDEN_PATTERNS.some((pattern) => pattern.test(text))
}

function isForbiddenMemoryCandidate(candidate: MemoryCandidate): boolean {
  if (candidate.kind === "quoted_untrusted") return true
  if (isForbiddenMemoryText(candidate.text)) return true
  return (
    candidate.kind === "instruction" &&
    INSTRUCTION_FORBIDDEN_PATTERNS.some((pattern) =>
      pattern.test(candidate.text)
    )
  )
}

function normalizeMemoryCandidates(
  parsed: Record<string, unknown>,
  evidence: MemoryEvidenceSegment[]
): MemoryCandidate[] {
  const evidenceById = new Map(evidence.map((segment) => [segment.id, segment]))
  const candidates = Array.isArray(parsed.candidates)
    ? parsed.candidates
    : Array.isArray(parsed.items)
      ? parsed.items
      : []
  const normalized: MemoryCandidate[] = []
  const seen = new Set<string>()

  for (const candidate of candidates.slice(0, 20)) {
    if (!candidate || typeof candidate !== "object") continue
    const record = candidate as Record<string, unknown>
    const text =
      typeof record.text === "string"
        ? clampMemoryFact(record.text)
        : typeof record.fact === "string"
          ? clampMemoryFact(record.fact)
          : ""
    if (!text) continue
    if (!validMemoryCategory(record.category)) continue
    if (!validMemoryCandidateKind(record.kind)) continue
    const sourceIds = Array.isArray(record.sourceIds)
      ? record.sourceIds.filter((id): id is string => typeof id === "string")
      : []
    if (sourceIds.length === 0) continue
    if (
      sourceIds.some((id) => evidenceById.get(id)?.trust !== "user_instruction")
    ) {
      continue
    }
    const id =
      typeof record.id === "string" && record.id.trim()
        ? record.id.trim().slice(0, 80)
        : `candidate-${normalized.length + 1}`
    const normalizedCandidate = {
      id,
      text,
      category: record.category,
      kind: record.kind,
      sourceIds: [...new Set(sourceIds)].slice(0, 5),
    }
    if (isForbiddenMemoryCandidate(normalizedCandidate)) continue
    const key = `${normalizedCandidate.category}:${normalizedCandidate.text.toLowerCase()}`
    if (seen.has(key)) continue
    seen.add(key)
    normalized.push(normalizedCandidate)
  }

  return normalized.slice(0, 12)
}

export function validatedMemoryCandidatesForTest(
  parsed: Record<string, unknown>,
  evidence: MemoryEvidenceSegment[]
): MemoryCandidate[] {
  return normalizeMemoryCandidates(parsed, evidence)
}

function parseFrontmatter(content: string): {
  frontmatter: string
  body: string
} {
  const match = /^(---\n[\s\S]*?\n---\n?)([\s\S]*)$/.exec(content)
  if (!match) return { frontmatter: "", body: content }
  return { frontmatter: match[1], body: match[2] }
}

function existingItems(content: string): string[] {
  const { body } = parseFrontmatter(content)
  return (
    body
      .replace(/<!--[\s\S]*?-->/g, "")
      .match(/^- .+/gm)
      ?.map((line) => line.slice(2).trim())
      .filter(Boolean) ?? []
  )
}

function factLines(content: string): string[] {
  return (
    content
      .match(/^- .+/gm)
      ?.map((line) => line.slice(2).trim())
      .filter(Boolean) ?? []
  )
}

function extractKeywords(summaryText: string): string[] {
  const keywords = new Set<string>()
  const lines = summaryText.match(/^- .+/gm) ?? []
  for (const line of lines) {
    const terms =
      line.match(
        /[\u4e00-\u9fff]{2,}|[A-Z][a-zA-Z0-9]+(?:\s+[A-Z][a-zA-Z0-9]+)*/g
      ) ?? []
    for (const term of terms.slice(0, 3)) keywords.add(term)
  }
  return [...keywords].slice(0, 15)
}

