const CONFIG_NAMES = [
  "playwright.config.ts",
  "playwright.config.mts",
  "playwright.config.js",
  "playwright.config.mjs",
  "playwright.config.cjs",
]

// Where the generated config goes: the workspace root, unless the user has a
// config of their own there; then inside the suite (`npx playwright test -c
// e2e`). Workspace-relative.
export async function suiteConfigPath(workspace: string): Promise<string> {
  for (const name of CONFIG_NAMES) {
    const file = path.join(workspace, name)
    if (!existsSync(file)) continue
    const text = await readFile(file, "utf8").catch(() => "")
    return text.includes(GENERATED_MARK)
      ? name
      : `${SUITE_DIR}/playwright.config.ts`
  }
  return "playwright.config.ts"
}

// A service's command as the user runs it from the workspace root: `cd`
// into its directory, its setup first, its port from the environment.
// shortcut: `{env:KEY}` reads the shell's environment, not the .env files the
// harness reads; load them in the command if a project needs it.
function webServerCommand(
  recipe: AppLaunch,
  service: AppService,
  ports: Record<string, number>
): string {
  const resolve = (text: string, own: number | null) =>
    text
      .replace(
        /\{port\}/g,
        own === null ? "" : `\${${service.portEnv ?? DEFAULT_PORT_ENV}:-${own}}`
      )
      .replace(/\{port:([^}]+)\}/g, (_all, key: string) =>
        String(ports[key.trim()] ?? "")
      )
      .replace(/\{env:([^}]+)\}/g, (_all, key: string) => `\${${key.trim()}}`)
  const own = service.port === "none" ? null : ports[service.key]
  const steps = [...globalSetup(recipe), ...serviceSetup(recipe, service.key)]
  const env = Object.entries(service.env ?? {}).map(
    ([key, value]) => `${key}="${resolve(value, own)}"`
  )
  const portEnv =
    own === null
      ? []
      : [
          `${service.portEnv ?? DEFAULT_PORT_ENV}=\${${service.portEnv ?? DEFAULT_PORT_ENV}:-${own}}`,
        ]
  const run = [...portEnv, ...env, resolve(service.command, own)].join(" ")
  const inDir = (cwd: string, command: string) =>
    cwd ? `(cd ${JSON.stringify(cwd)} && ${command})` : command
  return [
    ...steps.map((s) => inDir(s.cwd, resolve(s.command, own))),
    inDir(service.cwd, run),
  ].join(" && ")
}

// The config `npx playwright test` reads (plan 112.5): the suite as its test
// directory and a webServer per recipe service, so it starts the app the
// way the harness does. Fixed fallback ports, overridable from the
// environment; reuseExistingServer so a running app is used as is.
export function buildSuiteConfig(input: {
  recipe: AppLaunch
  // Workspace-relative, from where the config sits.
  testDir: string
  // The config's directory relative to the workspace root ("" or "e2e").
  configDir: string
}): string {
  const services = startOrder(input.recipe)
  const ports: Record<string, number> = {}
  let next = 3000
  for (const s of services)
    if (s.port !== "none")
      ports[s.key] = typeof s.port === "number" ? s.port : next++
  // The recipe's directories are workspace-relative.
  const up = input.configDir ? ".." : "."
  const json = (value: unknown) => JSON.stringify(value)
  const servers = services.map((s) => {
    const url =
      s.port !== "none" && "http" in s.ready
        ? `\`http://127.0.0.1:\${process.env.${s.portEnv ?? DEFAULT_PORT_ENV} ?? ${ports[s.key]}}${s.ready.http.startsWith("/") ? s.ready.http : `/${s.ready.http}`}\``
        : null
    return [
      "    {",
      `      // ${s.label}`,
      `      command: ${json(webServerCommand(input.recipe, s, ports))},`,
      `      cwd: ${json(up)},`,
      ...(url
        ? [`      url: ${url},`]
        : s.port !== "none"
          ? [`      port: ${ports[s.key]},`]
          : []),
      `      timeout: ${s.readyTimeoutMs ?? DEFAULT_READY_TIMEOUT_MS},`,
      "      reuseExistingServer: true,",
      "    },",
    ].join("\n")
  })
  const first = services.find((s) => s.port !== "none")
  return [
    `// ${GENERATED_MARK} from the app launch recipe (plan 112.5). It's`,
    "// regenerated at every acceptance gate: edit the recipe, not this file.",
    `// Run the suite with \`npx playwright test${input.configDir ? ` -c ${input.configDir}` : ""}\`.`,
    'import { defineConfig } from "@playwright/test"',
    "",
    "export default defineConfig({",
    `  testDir: ${json(input.testDir)},`,
    "  use: {",
    first
      ? `    baseURL: process.env.BASE_URL ?? \`http://127.0.0.1:\${process.env.${first.portEnv ?? DEFAULT_PORT_ENV} ?? ${ports[first.key]}}\`,`
      : "",
    "  },",
    ...(servers.length ? ["  webServer: [", ...servers, "  ],"] : []),
    "})",
    "",
  ]
    .filter((line) => line !== "")
    .join("\n")
    .concat("\n")
}

const README_NOTE = `# Acceptance suite

${GENERATED_MARK}'s acceptance gates write this Playwright suite: one test per
acceptance criterion, tagged \`@<storyRef> @AC-n\`.

Run it with \`npx playwright test\` (the generated \`playwright.config.ts\`
starts the app from the launch recipe). The workspace needs
\`@playwright/test\`: \`npm i -D @playwright/test && npx playwright install chromium\`.
Inside North Star the gates use a bundled copy when the workspace has none.
`

// Write the generated config (and, once, the suite's README) into the gate's
// worktree. Returns the workspace-relative paths written.
export async function writeSuiteConfig(
  workspace: string,
  recipe: AppLaunch
): Promise<string[]> {
  const configPath = await suiteConfigPath(workspace)
  const configDir = path.posix.dirname(configPath) === "." ? "" : SUITE_DIR
  await mkdir(path.join(workspace, SUITE_DIR), { recursive: true })
  await writeFile(
    path.join(workspace, configPath),
    buildSuiteConfig({
      recipe,
      testDir: configDir ? "." : `./${SUITE_DIR}`,
      configDir,
    })
  )
  const written = [configPath]
  const readme = path.join(workspace, SUITE_DIR, "README.md")
  if (!existsSync(readme)) {
    await writeFile(readme, README_NOTE)
    written.push(`${SUITE_DIR}/README.md`)
  }
  return written
}
