// The wave gate's QA step (plan 112.5). In a worktree at the integration
// head, with the app running, QA writes or extends ONE Playwright suite for
// every criterion in the batch, runs it whole with run_suite, and records
// the gate with record_gate. Tests are tagged `@<storyRef> @AC-n`; the tags
// map them to criteria. Committing the suite and finishing the gate happen
// when the run settles (integration.onGateSettled).

// Where the suite lives, workspace-relative.
export const SUITE_DIR = "e2e"
const SKIP = new Set(["node_modules", "test-results", "playwright-report"])
const SUITE_TIMEOUT_MS = 15 * 60_000
const GENERATED_MARK = "Generated by North Star"

// ── the suite on disk ───────────────────────────────────────────────────────

async function suiteFiles(dir: string, prefix = ""): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => [])
  const files: string[] = []
  for (const entry of entries) {
    if (SKIP.has(entry.name) || entry.name.startsWith(".")) continue
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name
    if (entry.isDirectory())
      files.push(...(await suiteFiles(path.join(dir, entry.name), rel)))
    else if (entry.isFile()) files.push(rel)
  }
  return files.sort()
}

// The suite directory's content hash: a record counts only results on the
// suite as it is.
export async function suiteHash(workspace: string): Promise<string> {
  const dir = path.join(workspace, SUITE_DIR)
  const hash = createHash("sha256")
  for (const file of await suiteFiles(dir)) {
    hash.update(`${file}\0`)
    hash.update(await readFile(path.join(dir, file)))
    hash.update("\0")
  }
  return hash.digest("hex").slice(0, 16)
}

// ── the run's gate ──────────────────────────────────────────────────────────

function rootRun(run: ProcessRun): ProcessRun {
  let current = run
  for (let depth = 0; current.parentPhaseRunId && depth < 16; depth++) {
    const parent = processes.getPhaseRun(current.parentPhaseRunId)
    const parentRun = parent ? processes.getProcessRun(parent.runId) : undefined
    if (!parentRun) break
    current = parentRun
  }
  return current
}

export interface GateContext {
  root: ProcessRun
  phaseRun: ProcessPhaseRun
  gate: WaveGate
  feature: Feature
  milestone: Milestone
  // The batch, then every other done story of the feature (its tests are in
  // the suite too).
  stories: Array<GateStory & { userStory: UserStory }>
}

export function gateContext(
  processRunId: string,
  phaseRunId: string
):
  | { ok: true; ctx: GateContext }
  | { ok: false; code: string; message: string } {
  const unavailable = {
    ok: false as const,
    code: "not_gate_step",
    message: "Only the QA step of a milestone's acceptance gate can do this.",
  }
  const run = processes.getProcessRun(processRunId)
  const phaseRun = processes.getPhaseRun(phaseRunId)
  if (!run || !phaseRun) return unavailable
  const root = rootRun(run)
  const link = root.missionControl
  if (link?.hook !== "after_each_wave") return unavailable
  const gate = waveGates.getWaveGateByRun(link.playbookRunId)
  const feature = features.getFeature(link.featureId)
  const milestone = gate ? features.getMilestone(gate.milestoneId) : null
  if (!gate || !feature || !milestone) return unavailable
  if (gate.status !== "running")
    return {
      ok: false,
      code: "run_finished",
      message: "This acceptance gate has already finished.",
    }
  const waivers = gateWaivers(feature.id)
  const batch = new Set(gate.storyIds)
  const milestones = new Map(
    features.listMilestones(feature.id).map((m) => [m.id, m])
  )
  const stories = [...milestones.values()]
    .flatMap((m) => features.listUserStories(m.id))
    .filter((s) => batch.has(s.id) || s.status === "done")
    .map((s) => ({
      userStory: s,
      userStoryId: s.id,
      key: s.key,
      storyRef: userStoryRef(feature, milestones.get(s.milestoneId)!, s),
      criteria: userStoryCriteria(s),
      batch: batch.has(s.id),
      waived: waivedCriteria(s, waivers),
    }))
    .sort((a, b) => Number(b.batch) - Number(a.batch))
  return {
    ok: true,
    ctx: { root, phaseRun, gate, feature, milestone, stories },
  }
}

