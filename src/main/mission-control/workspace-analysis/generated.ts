function under(root: string, file: string) {
  return !root || file === root || file.startsWith(`${root}/`)
}
function rootFor(roots: ProjectRoot[], file: string): string {
  return (
    roots
      .map((r) => r.dir)
      .filter((dir) => under(dir, file))
      .sort((a, b) => b.length - a.length)[0] ?? ""
  )
}
// Run a command from the workspace directory in `root`.
export function inRoot(root: string, command: string) {
  return root ? `cd ${root} && ${command}` : command
}

function scripts(pkg: string | null): Record<string, string> {
  if (!pkg) return {}
  try {
    const json = JSON.parse(pkg) as { scripts?: Record<string, string> }
    return json.scripts ?? {}
  } catch {
    return {}
  }
}

function runner(root: ProjectRoot): string {
  const e = root.ecosystems
  return e.includes("pnpm")
    ? "pnpm run"
    : e.includes("yarn")
      ? "yarn run"
      : e.includes("bun")
        ? "bun run"
        : "npm run"
}

function makeTargets(makefile: string | null): string[] {
  if (!makefile) return []
  return [...makefile.matchAll(/^([A-Za-z0-9_.-]+)\s*:(?!=)/gm)].map(
    (m) => m[1]
  )
}

