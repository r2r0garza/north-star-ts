// Stage 4 (plan 106.11): files a project generates rather than writes by
// hand, paired with the command that regenerates them, so parallel stories
// regenerate on merge instead of hand-merging (or conflicting on) them.
// Globs and commands are workspace-relative, as GeneratedFilesRule is applied
// (the merge queue runs the command from the workspace directory).

export interface GeneratedGroup {
  key: string
  // What produces them, for the title: "protobuf", "Prisma client", "pnpm lockfile".
  label: string
  root: string
  paths: string[]
  command: string | null
  confidence: FindingConfidence
  evidence: Omit<Evidence, "id">[]
  // A prerequisite the command needs (a running database).
  needs?: string
  lockfile?: boolean
}

export interface GeneratedInput {
  tracked: string[]
  roots: ProjectRoot[]
  read: Reader
  // Newest first; workspace-relative paths per commit.
  history: string[][]
  // Recipe contexts per root dir, for lock regeneration commands.
  contexts: Map<string, RecipeContext>
}

