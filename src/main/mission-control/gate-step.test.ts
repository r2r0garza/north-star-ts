import { describe, expect, it, vi } from "vitest"

vi.mock("../db/connection", () => ({ getDb: () => undefined }))

import { buildSuiteConfig, touchedTests } from "./gate-step"
import type { AppLaunch } from "../db/types"

// The wave suite's generated config and change detection (plan 112.5).

describe("buildSuiteConfig", () => {
  const recipe: AppLaunch = {
    setup: [{ label: "Migrate", command: "npm run migrate", cwd: "api" }],
    services: [
      {
        key: "api",
        label: "API",
        command: "npm start",
        cwd: "api",
        port: "auto",
        ready: { http: "/health" },
        source: "user",
      },
      {
        key: "web",
        label: "Web",
        command: "npm run dev -- --port {port}",
        cwd: "web",
        port: 5173,
        env: { API_URL: "http://127.0.0.1:{port:api}" },
        ready: { http: "/" },
        readyTimeoutMs: 60_000,
        source: "user",
      },
    ],
  }

  it("starts every recipe service as a webServer, setup folded in", () => {
    const config = buildSuiteConfig({ recipe, testDir: "./e2e", configDir: "" })
    expect(config).toContain("Generated by North Star")
    expect(config).toContain('testDir: "./e2e"')
    // Dependencies first; the setup runs before the service, in its folder.
    expect(config.indexOf("// API")).toBeLessThan(config.indexOf("// Web"))
    expect(config).toContain(
      'command: "(cd \\"api\\" && npm run migrate) && (cd \\"api\\" && PORT=${PORT:-3000} npm start)"'
    )
    // A fixed port is kept; an auto one gets a fixed fallback, overridable.
    expect(config).toContain("--port ${PORT:-5173}")
    expect(config).toContain('API_URL=\\"http://127.0.0.1:3000\\"')
    expect(config).toContain(
      "url: `http://127.0.0.1:${process.env.PORT ?? 3000}/health`"
    )
    expect(config).toContain("timeout: 60000")
    expect(config.match(/reuseExistingServer: true/g)).toHaveLength(2)
    expect(config).toContain(
      "baseURL: process.env.BASE_URL ?? `http://127.0.0.1:${process.env.PORT ?? 3000}`"
    )
  })

  it("runs from inside the suite when the user has a root config of their own", () => {
    const config = buildSuiteConfig({ recipe, testDir: ".", configDir: "e2e" })
    expect(config).toContain("npx playwright test -c e2e")
    expect(config).toContain('cwd: ".."')
  })

  it("has no webServer for a project with no services", () => {
    expect(
      buildSuiteConfig({
        recipe: { services: [] },
        testDir: "./e2e",
        configDir: "",
      })
    ).not.toContain("webServer")
  })
})

describe("touchedTests", () => {
  const before = [
    'test("shows the list @F.M1.list @AC-1", async ({ page }) => {',
    '  await page.goto("/")',
    '  await expect(page.getByRole("list")).toBeVisible()',
    "})",
  ].join("\n")

  it("ignores tests added next to an earlier story's", () => {
    const diff = [
      "@@ -4,0 +5,3 @@",
      '+test("adds @F.M1.add @AC-1", async () => {',
      "+})",
    ].join("\n")
    expect(touchedTests(before, diff)).toBe("")
  })

  it("flags an edit inside an earlier story's test", () => {
    const diff = [
      "@@ -3 +3 @@",
      '-  await expect(page.getByRole("list")).toBeVisible()',
      '+  await expect(page.getByRole("table")).toBeVisible()',
    ].join("\n")
    expect(touchedTests(before, diff)).toContain("@F.M1.list")
  })

  it("ignores a line removed and added back as is (a final newline)", () => {
    const diff = ["@@ -4 +4,2 @@", "-})", "+})", '+test("x", () => {})'].join(
      "\n"
    )
    expect(touchedTests(before, diff)).toBe("")
  })
})
